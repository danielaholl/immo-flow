-- Conversations policies
CREATE POLICY "Users can view conversations they participate in"
  ON conversations FOR SELECT
  TO authenticated
  USING (
    buyer_id IN (SELECT id FROM user_profiles WHERE user_id = public.current_user_id()) OR
    seller_id IN (SELECT id FROM user_profiles WHERE user_id = public.current_user_id())
  );

-- Messages policies
CREATE POLICY "Users can view messages in their conversations"
  ON messages FOR SELECT
  TO authenticated
  USING (
    conversation_id IN (
      SELECT id FROM conversations WHERE
        buyer_id IN (SELECT id FROM user_profiles WHERE user_id = public.current_user_id()) OR
        seller_id IN (SELECT id FROM user_profiles WHERE user_id = public.current_user_id())
    )
  );

CREATE POLICY "Users can insert messages in their conversations"
  ON messages FOR INSERT
  TO authenticated
  WITH CHECK (
    conversation_id IN (
      SELECT id FROM conversations WHERE
        buyer_id IN (SELECT id FROM user_profiles WHERE user_id = public.current_user_id()) OR
        seller_id IN (SELECT id FROM user_profiles WHERE user_id = public.current_user_id())
    )
  );

-- Property statistics policies
CREATE POLICY "Anyone can view property statistics"
  ON property_statistics FOR SELECT
  TO public
  USING (true);

CREATE POLICY "Property owners can update their statistics"
  ON property_statistics FOR UPDATE
  TO authenticated
  USING (
    property_id IN (SELECT id FROM properties WHERE user_id = public.current_user_id())
  );
